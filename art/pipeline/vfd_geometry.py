# 16-segment VFD geometry. One source of truth for the display's segment shapes and glyph table:
#   python vfd_geometry.py            writes ../../Source/VfdGeometry.h
#   python vfd_geometry.py out.h      writes out.h
# Units: design px. A glyph box is GW x GH, origin top-left; the glyph is sheared (top leans right) by SHEAR.
import math, json

GW, GH = 9.0, 19.0          # glyph box
T = 1.75                    # outer bar thickness
TV = 1.60                   # centre vertical thickness
TD = 1.85                   # diagonal thickness
GAP = 0.50                  # visible gap between neighbouring segments
SHEAR = 0.13                # top leans right by GH * SHEAR
PITCH = 14.1                # distance between glyph origins
DP_R = 0.95                 # decimal point radius

XC, YM = GW / 2, GH / 2

def inset(poly, d):
    """Shrink a convex polygon by d (all edges move inwards by d)."""
    n = len(poly)
    cx = sum(p[0] for p in poly) / n; cy = sum(p[1] for p in poly) / n
    lines = []
    for i in range(n):
        p, q = poly[i], poly[(i + 1) % n]
        ex, ey = q[0] - p[0], q[1] - p[1]
        L = math.hypot(ex, ey)
        if L < 1e-9: continue
        nx, ny = -ey / L, ex / L
        if nx * (cx - p[0]) + ny * (cy - p[1]) < 0: nx, ny = -nx, -ny
        lines.append(((p[0] + nx * d, p[1] + ny * d), (ex / L, ey / L)))
    out = []
    for i in range(len(lines)):
        (p1, d1), (p2, d2) = lines[i - 1], lines[i]
        det = d1[0] * (-d2[1]) - d1[1] * (-d2[0])
        if abs(det) < 1e-9: out.append(p2); continue
        rx, ry = p2[0] - p1[0], p2[1] - p1[1]
        s = (rx * (-d2[1]) - ry * (-d2[0])) / det
        out.append((p1[0] + d1[0] * s, p1[1] + d1[1] * s))
    return out

def strip(p0, p1, hw):
    dx, dy = p1[0] - p0[0], p1[1] - p0[1]; L = math.hypot(dx, dy)
    nx, ny = -dy / L * hw, dx / L * hw
    return [(p0[0] + nx, p0[1] + ny), (p1[0] + nx, p1[1] + ny), (p1[0] - nx, p1[1] - ny), (p0[0] - nx, p0[1] - ny)]

def mirror_x(poly): return [(GW - x, y) for x, y in poly][::-1]
def mirror_y(poly): return [(x, GH - y) for x, y in poly][::-1]

# --- raw segments (before gaps)
a1 = [(0, 0), (XC, 0), (XC, T), (T, T)]
f  = [(0, 0), (T, T), (T, YM - T / 2), (0, YM)]
g1 = [(0, YM), (T, YM - T / 2), (XC, YM - T / 2), (XC, YM + T / 2), (T, YM + T / 2)]
i_ = [(XC - TV / 2, T), (XC + TV / 2, T), (XC + TV / 2, YM - T / 2), (XC - TV / 2, YM - T / 2)]
P0 = (T + 0.25, T + 0.25); P1 = (XC - TV / 2 - 0.35, YM - T / 2 - 0.45)
h  = strip(P0, P1, TD / 2)

SEG = {}
SEG['a1'] = a1;             SEG['a2'] = mirror_x(a1)
SEG['f'] = f;               SEG['b'] = mirror_x(f)
SEG['e'] = mirror_y(f);     SEG['c'] = mirror_y(mirror_x(f))
SEG['d1'] = mirror_y(a1);   SEG['d2'] = mirror_y(mirror_x(a1))
SEG['g1'] = g1;             SEG['g2'] = mirror_x(g1)
SEG['i'] = i_;              SEG['l'] = mirror_y(i_)
SEG['h'] = h;               SEG['j'] = mirror_x(h)
SEG['k'] = mirror_y(h);     SEG['m'] = mirror_y(mirror_x(h))
ORDER = ['a1', 'a2', 'b', 'c', 'd2', 'd1', 'e', 'f', 'g1', 'g2', 'h', 'i', 'j', 'k', 'l', 'm']   # bit 0..15

def shear(p): return (p[0] + (GH - p[1]) * SHEAR, p[1])
POLY = {k: [shear(q) for q in inset(SEG[k], GAP / 2)] for k in ORDER}
DP = shear((GW, GH))   # placeholder, DP centre computed below
DP_C = (GW + 1.35 + 0.0, GH - DP_R - 0.05)

# --- glyph table: segment sets
S = lambda s: set(s.split())
G = {
 ' ': S(''),
 'A': S('a1 a2 b c f e g1 g2'), 'B': S('a1 a2 b c d1 d2 g2 i l'), 'C': S('a1 a2 f e d1 d2'),
 'D': S('a1 a2 b c d1 d2 i l'), 'E': S('a1 a2 f e d1 d2 g1 g2'), 'F': S('a1 a2 f e g1 g2'),
 'G': S('a1 a2 f e d1 d2 c g2'), 'H': S('f e b c g1 g2'), 'I': S('a1 a2 d1 d2 i l'),
 'J': S('b c d1 d2 e'), 'K': S('f e g1 j m'), 'L': S('f e d1 d2'),
 'M': S('f e b c h j'), 'N': S('f e b c h m'), 'O': S('a1 a2 b c d1 d2 e f'),
 'P': S('a1 a2 b f e g1 g2'), 'Q': S('a1 a2 b c d1 d2 e f m'), 'R': S('a1 a2 b f e g1 g2 m'),
 'S': S('a1 a2 f g1 g2 c d1 d2'), 'T': S('a1 a2 i l'), 'U': S('f e b c d1 d2'),
 'V': S('f e k j'), 'W': S('f e b c k m'), 'X': S('h j k m'), 'Y': S('h j l'),
 'Z': S('a1 a2 j k d1 d2'),
 '0': S('a1 a2 b c d1 d2 e f j k'), '1': S('b c j'), '2': S('a1 a2 b g1 g2 e d1 d2'),
 '3': S('a1 a2 b c d1 d2 g1 g2'), '4': S('f b g1 g2 c'), '5': S('a1 a2 f g1 g2 c d1 d2'),
 '6': S('a1 a2 f e g1 g2 c d1 d2'), '7': S('a1 a2 b c'), '8': S('a1 a2 b c d1 d2 e f g1 g2'),
 '9': S('a1 a2 b c f g1 g2 d1 d2'),
 '-': S('g1 g2'), '+': S('g1 g2 i l'), '/': S('j k'), '%': S('f c j k'), ':': S('i l'),
}
def mask(ch):
    m = 0
    for s in G[ch]: m |= 1 << ORDER.index(s)
    return m

def write_header(path):
    L = []
    L.append('// Generated by art/pipeline/vfd_geometry.py. Do not edit by hand.')
    L.append('#pragma once')
    L.append('namespace vfd')
    L.append('{')
    L.append(f'    constexpr float kGlyphW = {GW}f, kGlyphH = {GH}f, kPitch = {PITCH}f, kShear = {SHEAR}f, kDpR = {DP_R}f;')
    L.append(f'    constexpr float kDpX = {DP_C[0]:.4f}f, kDpY = {DP_C[1]:.4f}f;')
    L.append('    constexpr int kSegments = 16;')
    L.append('    // segment bit order: ' + ' '.join(ORDER))
    L.append('    struct Seg { int n; float p[6][2]; };')
    L.append('    constexpr Seg kSeg[kSegments] = {')
    for k in ORDER:
        pts = POLY[k]
        pp = ', '.join('{%.4ff, %.4ff}' % q for q in pts) + ''.join(', {0.0f, 0.0f}' for _ in range(6 - len(pts)))
        L.append(f'        {{ {len(pts)}, {{ {pp} }} }},   // {k}')
    L.append('    };')
    L.append('    struct Glyph { char ch; unsigned short segs; };')
    L.append('    constexpr Glyph kGlyphs[] = {')
    for ch in G:
        L.append("        { '%s', 0x%04X }," % (ch, mask(ch)))
    L.append('    };')
    L.append('}')
    open(path, 'w').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    import sys, os
    here = os.path.dirname(os.path.abspath(__file__))
    write_header(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'Source', 'VfdGeometry.h'))
